<p><strong>ДЕКЛАРАЦИЯ 100X ОБ АСТЕРОИДАХ</strong></p>
<p>Декларация 100x об астероидах, призывающая к таким действиям, подписана сотнями астронавтов, учёных, деятелей искусства и лидеров бизнеса и технологий, а также тысячами частных лиц. Использование существующих и новых технологий для обнаружения и отслеживания астероидов, а также демонстрация возможностей отклонения для предотвращения будущих столкновений с астероидами могут стать величайшим достижением человечества.</p>
<p>День астероидов когда-нибудь сможет помочь спасти ВСЕ виды на этой планете, привлекая внимание к работе, которая ведётся сейчас на местном и глобальном уровне в этой области. День астероидов рассказывает о мужчинах и женщинах, посвятивших свою жизнь науке и технологиям, которые сделают возможной планетарную защиту. Вы можете помочь, организовав местное мероприятие и подписав Декларацию 100X.</p>
<p>Мы продолжаем узнавать об эволюции Солнечной системы и роли астероидов в истории космоса и Земли. Небольшие столкновения происходят регулярно, и NASA сообщает, что мировые усилия на сегодняшний день позволили обнаружить около 95% астероидов, способных уничтожить жизнь на Земле в том виде, в каком мы её знаем, если бы один из них упал. Исходя из того, что известно о популяции околоземных объектов (NEO) и истории столкновений Земли, учёные предсказывают, что когда-нибудь в будущем Земля переживёт ещё одно крупномасштабное столкновение — просто они не знают, когда именно.</p>
<p>Наша цель — повысить осведомлённость общественности о науке об астероидах и планах планетарной защиты.</p>
