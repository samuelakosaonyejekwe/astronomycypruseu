<p>Каждый год Планетарий и обсерватория «Китион» организует и координирует мероприятия на Кипре, а также онлайн-мероприятия, доступные для зрителей по всему миру.</p>
<p>Планетарий и обсерватория «Китион» в течение всего года подчёркивает важность знаний об астероидах.</p>
