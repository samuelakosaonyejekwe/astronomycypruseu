<div class="block"><p><strong>ИСТОРИЯ СОЗДАНИЯ ДНЯ АСТЕРОИДОВ</strong></p>
<p>День астероидов — это динамичная просветительская и образовательная программа, цель которой — вдохновить мир на интерес к астероидам: их роли в формировании нашей Солнечной системы, тому, как мы можем использовать их ресурсы, как астероиды могут проложить путь для будущих исследований и, наконец, как мы можем защитить нашу планету от столкновений с астероидами. Мероприятия Дня астероидов проходят 30 июня каждого года в годовщину Тунгусского события 1908 года. Мероприятия Дня астероидов в основном организуются независимо по всему миру для людей всех возрастов и в большинстве случаев бесплатны. День астероидов — это программа Фонда астероидов (Asteroid Foundation), некоммерческой организации из Люксембурга.</p>
<p>День астероидов был основан в 2014 году доктором Брайаном Мэем, астрофизиком и соло-гитаристом группы QUEEN, совместно с Даникой Ремми, президентом Фонда B612, Расти Швейкартом, астронавтом Apollo 9, и кинорежиссёром Григом Рихтерсом. В 2016 году Организация Объединённых Наций официально объявила День астероидов международным днём информирования и просвещения об астероидах. Совместно с Организацией Объединённых Наций, космическими агентствами, школами и университетами День астероидов организуют сети сторонников, которые проводят мероприятия по всему миру 30 июня и в любой другой день года, который определяют независимые группы.</p>
<p>Для запуска образовательных программ Дня астероидов в 2014 году участники астероидного сообщества составили и опубликовали петицию, чтобы заручиться общественной поддержкой образования об астероидах, и призвали правительства ускорить финансирование программ по поиску астероидов. Сегодня эта петиция — Декларация 100X об астероидах — подписана сотнями выдающихся людей по всему миру, включая лидеров науки, технологий и бизнеса, а также более чем 125 астронавтами.</p>
<p>Благодаря своим партнёрам и сторонникам, и в особенности правительству Люксембурга, где находится штаб-квартира Фонда, День астероидов добился значительных успехов в просвещении мира об астероидах. В своей работе мы делимся информацией и рассказываем о науке, возможностях и рисках, связанных с астероидами. С первых мероприятий в 2015 году движение росло в геометрической прогрессии. Через День астероидов мы продолжаем вдохновлять людей и молодые умы смотреть в небо и увлекаться нашей Солнечной системой.</p>
<div class="blocks"><div class="row split reverse"><div class="block media"><p><img alt="" data-nw="1203" decoding="async" height="411" loading="lazy" src="/images/asteroid-day/asteroidday_title.jpg" width="550"/></p></div><div class="block"><p class="short"><strong>МИССИЯ ДНЯ АСТЕРОИДОВ</strong></p><p>День астероидов отмечается ежегодно 30 июня.</p><p>Это глобальная информационная кампания, в рамках которой люди со всего мира собираются вместе, чтобы узнать об астероидах, об опасности столкновения, которую они могут представлять, и о том, что мы можем сделать, чтобы защитить нашу планету, семьи, сообщества и будущие поколения от будущих столкновений с астероидами.</p><p>День астероидов отмечается каждый год в годовщину крупнейшего столкновения в недавней истории — Тунгусского события 1908 года в Сибири. Сравнительно небольшой астероид — около 40 метров в поперечнике, размером с обычное офисное здание, — опустошил необитаемую территорию, по площади сравнимую с крупным мегаполисом.</p><p>В День астероидов проходят крупные и небольшие региональные мероприятия — от лекций и других образовательных программ до живых концертов и более широких общественных событий, — чтобы повысить осведомлённость общественности о необходимости усиленного обнаружения и отслеживания астероидов.</p></div></div></div>





