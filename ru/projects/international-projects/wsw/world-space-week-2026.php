<h2>Ознакомьтесь с основными событиями Всемирной недели космоса 2026</h2>
<h2>Что такое Всемирная неделя космоса?</h2>
<p>Всемирная неделя космоса — это международный праздник науки и технологий и их вклада в улучшение условий жизни человечества. Генеральная Ассамблея Организации Объединённых Наций объявила в 1999 году, что Всемирная неделя космоса будет проводиться ежегодно с 4 по 10 октября. Эти даты отмечают два события:</p>
<ul>
<li>4 октября 1957 года: запуск первого искусственного спутника Земли «Спутник-1», открывший путь к освоению космоса</li>
<li>10 октября 1967 года: подписание Договора о принципах деятельности государств по исследованию и мирному использованию космического пространства, включая Луну и другие небесные тела.</li>
</ul>
<h2><strong>Где и как отмечается Всемирная неделя космоса?</strong></h2>
<p>Всемирная неделя космоса состоит из образовательных и просветительских космических мероприятий, которые проводят космические агентства, аэрокосмические компании, школы, планетарии, музеи и астрономические клубы по всему миру в единые сроки. Эти синхронизированные космические мероприятия привлекают больше внимания общественности и СМИ. Всемирная неделя космоса 2025 года достигла рекордного масштаба:</p>
<ul>
<li>До 50 000 мероприятий</li>
<li>Мероприятия в 102 странах</li>
</ul>
<p>Всемирная неделя космоса координируется Организацией Объединённых Наций при поддержке Ассоциации Всемирной недели космоса (WSWA). WSWA руководит глобальной командой национальных координаторов, которые продвигают проведение Всемирной недели космоса в своих странах.</p>
