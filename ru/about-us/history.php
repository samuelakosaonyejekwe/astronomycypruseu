<p>ПЛАНЕТАРИЙ И ОБСЕРВАТОРИЯ «КИТИОН» — это частная инициатива. Он был основан господином Георгием Труллиасом и официально зарегистрирован как организация 14 февраля 2008 года.</p>
<p><em><strong>Для нас большая честь носить знаковое имя древнего города Ларнаки — «КИТИОН».</strong></em></p>
<p>Обладая большой страстью к науке и к обмену знаниями с широкой публикой, господин Георгий Труллиас собрал вокруг себя больше людей и учёных, разделявших ту же мечту и ту же страсть, и так начался наш путь.</p>
<p>Миссия нашей организации — содействовать изучению, экспериментам и информированию в области астрономии, астрофизики, космических наук, а также в области других естественных и социальных прикладных наук.</p>
<p>ПЛАНЕТАРИЙ И ОБСЕРВАТОРИЯ «КИТИОН» проводит множество различных мероприятий, связанных с наукой и технологиями. С 2008 года нас посетили тысячи местных жителей и иностранных туристов, детей, школ, организованных групп и учёных.</p>
<p>С момента основания ПЛАНЕТАРИЙ И ОБСЕРВАТОРИЯ «КИТИОН» проявляет большую социальную ответственность и участвует в благотворительных инициативах. Он помогал собирать средства для общинного рынка, а также поддерживал онкологических больных и другие уязвимые группы общины.</p>
<p> Стоит отметить наше сотрудничество с полицией и поддержку её программ борьбы с наркотиками. ПЛАНЕТАРИЙ И ОБСЕРВАТОРИЯ «КИТИОН» сотрудничает с общественно полезными организациями и благотворительными фондами (например, Фонд Кристины А. Апостолу, Ассоциация онкологических больных и друзей и др.) и поддерживает их цели, собирая деньги, одежду, продукты питания и игрушки для нуждающихся.</p>
