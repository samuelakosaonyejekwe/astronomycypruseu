<p>Мы очень гордимся назначением в состав организационного комитета Международной астрофизической конференции, которая прошла в июне 2015 года в UCLAN Cyprus. Для нас это большая честь, оказанная от имени организаторов конференции — Института математики, астрономии и физики имени Джеремайи Хоррокса в Престоне при UCLAN, Англия. Это признание нашей работы в мировом научном сообществе. Оно продвигает Кипр в мире и с 2008 года способствует развитию науки и астротуризма на Кипре.</p>
<p>В 2016 году мы успешно представили первый ежегодный кипрский проект под названием «COSMIC LIGHT REACHES CYPRUS 2016» («Cosmic Light Reaches Cyprus 2016»), который был отобран Международным астрономическим союзом (IAU) среди лучших проектов мира и стал продолжением празднования Международного года света 2015 и светоориентированных технологий ЮНЕСКО.</p>
<p>В 2017 году был представлен новый, более насыщенный проект под названием «Starry Bridges», который вновь оказался среди лучших проектов мира. Он был посвящён науке астрономии и её влиянию на культуру.</p>
<p>В январе 2018 года нам удалось принять участие в проекте и напрямую связаться с астронавтом Марком Ванде Хаем, находившимся на борту Международной космической станции (МКС). В конце года у нас вышла новая публикация в журнале IEEE, посвящённая околоземным объектам (NEO).</p>
<p>В области исследований мы сделали много открытий новых (предварительных) астероидов в Главном поясе астероидов в сотрудничестве с NASA и зарубежными университетами. Одно из наших важнейших открытий — АСТЕРОИД 2019 AN16. У нас также есть несколько открытий в области археоастрономии, которые были опубликованы в одних из самых авторитетных научных журналов. Вместе с тем мы продолжаем наши исследования в упомянутых выше областях.</p>
<p>Стоит отметить, что у нас действует экспозиция «Геология и ископаемые Кипра», где посетитель может узнать о возникновении острова, первых его обитателях, вымершем эндемичном карликовом гиппопотаме и карликовых слонах, а также о явлении карликовости, которое происходит на островах. Новая космическая экспозиция даёт посетителям возможность увидеть нашу коллекцию метеоритов и космической еды, а также памятные предметы других космических миссий.</p>
<p>Наши сотрудники работают на добровольной основе. Это учёные, студенты, а также обычные граждане, которые интересуются нашими проектами и разделяют нашу страсть.</p>
<p>Для дальнейшего роста и расширения наших проектов нам нужны средства, ресурсы и поддержка нашей организации, чтобы она могла выжить в это трудное время. С момента основания мы не получали финансирования ни из каких источников; вместо этого наши сотрудники вкладывали своё личное время и деньги. Все они заслуживают большой благодарности и глубокого уважения со стороны нашей команды.</p>
<p>Мы всегда открыты для сотрудничества, совместной деятельности и поддержки в развитии нашего нового Научного центра, Планетария и Обсерватории. </p>
<p>Наши методы обучения и общения с публикой дают посетителям возможность почувствовать красоту звёздного неба с помощью простых научных и занимательных методов и осознать место человека в Солнечной системе и во Вселенной.</p>
<p>Словами невозможно описать восторг посетителей, когда они наблюдают небесные объекты в наши телескопы. Они путешествуют в мире чудес и с нетерпением ждут возможности узнать больше. </p>
<p>ПЛАНЕТАРИЙ И ОБСЕРВАТОРИЯ «КИТИОН», как первопроходец и лидер на Кипре в области астрономии и астрофизики, имея опыт и множество прикладных проектов с 2008 года, стремится вовлечь новое поколение в науку и технологии, и особенно в науку астрономии и астрофизики.</p>
