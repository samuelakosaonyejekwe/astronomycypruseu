<p>Замедленная киносъёмка - это метод, при котором частота, с которой снимаются кадры пленки (частота кадров) гораздо больше,  чем частота, используемая для просмотра последовательности. При воспроизведении с нормальной скоростью кажется,  что явление замедляется. </p>


