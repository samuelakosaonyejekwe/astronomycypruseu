<p class="short">BEND ASTRONOMY MEETUP (OREGON, USA)</p>

<p>The Bend Astronomy Meetup was established in October, 2015. The first meeting happened during the closing ceremony of <a href="/en/projects/international-projects/world-space-week.php">World Space Week</a>. That day there was a teleconference between Bend Astronomy Meetup and the KITION PLANETARIUM &amp; OBSERVATORY which were divided by 10 hours of time zones. There were just 5 people from Bend at that meeting, though now Meetup has a few hundreds members.</p>
<p>The dark skies around Bend are ideal for astronomy. There are many excellent telescopes in the area as well as people who know their way around the celestial objects. The group meets to make observations of eclipses, meteor showers, transits, deep sky objects, and more. It educates the public (sometimes right on the sidewalk), shares looks through telescopes and visit local observatories like Pine Mountain and Sun River. There are online events like watching a video stream from a remote eclipse to having a video call with an astronomy club in another country.</p>
<p>Starting from 2015 we cooperate in practical astronomy, in archeoastronomy and in August 2017 organized the observations of total solar eclipse. Visit the official site of <a href="https://www.meetup.com/Bend-Astronomy-Meetup/" rel="noopener noreferrer" target="_blank">Bend Astronomy Meetup</a> for more information. </p>
