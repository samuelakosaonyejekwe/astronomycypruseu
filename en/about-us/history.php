<h2>OUR HISTORY... THE MILESTONES OF OUR EVOLUTION...</h2>

<p>The "KITION PLANETARIUM &amp; OBSERVATORY" is a private initiative. It was founded by Mr. George Troullias, and was officially registered as an organization, on February 14, 2008.</p>
<p><em><strong>It is a great honour for us to bear the landmark name of the ancient city of Larnaca, “KITION”.</strong></em></p>
<p>With a lot of passion in science and in sharing the knowledge among the general public, Mr. George Troullias gathered more people and scientists who shared the same dream and passion and the journey began.</p>
<p>The mission of our organization is to promote the study, experimentation and information in the fields of astronomy, astrophysics, space science as well as the fields of other physical and social applied sciences.</p>
<p>The "KITION PLANETARIUM &amp; OBSERVATORY" carries out many different activities related to science and technology. Thousands of locals and foreign tourists, children, schools, organized groups, and scientists have visited us since 2008.</p>
<p>Since it was founded, the "KITION PLANETARIUM &amp; OBSERVATORY" has shown great social responsibility and participated in charity initiatives. It has contributed in fundraising for the communal market and to support cancer patients and other vulnerable groups in the community.</p>
<p> It is worth mentioning our cooperation with the police and our support to their programs in fighting against drugs. The "KITION PLANETARIUM &amp; OBSERVATORY" collaborates with public benefit institutions and charity foundations (e.g. Christina A. Apostolou Foundation, Association of Cancer Patients and Friends, etc.) and supports their cause to fundraise for money, clothes, food and toys for those in need.</p>
