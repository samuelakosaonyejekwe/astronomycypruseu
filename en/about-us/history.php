<p>We are very proud to point, the appointment as part of the organizing committee for the International Astrophysics Conference that took place in June 2015 at UCLAN Cyprus. It is a great honour for us, on behalf of the conference organizers, the Jeremiah Horrocks Institute for Mathematics, Astronomy and Physics of Preston at UCLAN England. This is a return for our work being recognized in the global scientific community. It promotes Cyprus around the world and helps the development of science and astrotourism in Cyprus since 2008.</p>
<p>In 2016 we successfully introduced the first annual Cypriot project named "COSMIC LIGHT REACHES CYPRUS 2016" ("Cosmic Light Reaches Cyprus 2016") which was selected among the best projects in the world by the International Astronomical Union (IAU) and was an extension of the celebrations of the World Year of Light 2015 and UNESCO Light-Based Technologies.</p>
<p>In 2017, a new and more enriched project named "Starry Bridges" was introduced, which was again among the best projects in the world. It involved the science of astronomy and its influence on culture.</p>
<p>In January 2018, we achieved to join a project and directly communicate with astronaut Mark Vande Hei who was on-board the International Space Station (ISS). At the end of the year we had a new publication in the IEEE journal related to Near Earth Objects (NEOs).</p>
<p>In the field of research we have made many discoveries of new (preliminary) asteroids in the Main Asteroid Zone in collaboration with NASA and universities abroad. One of our most important discoveries is the ASTEROID 2019 AN16. We also have several discoveries in the field of archaeoastronomy, which have been published by some of the most respected scientific journals. At the same time we continue our research in the areas of the above mentioned fields.</p>
<p>It is worth mentioning that we maintain an exhibition of Cypriot Geology and Fossils, where the visitor can learn about the creation of the island, the first inhabitants, the extinct endemic dwarf hippopotamus and dwarf elephants, and the phenomenon of dwarfism which occurs on islands. A new space exhibition gives the opportunity to visitors to look at our collection of meteorites and space food as well as other space missions memorabilia.</p>
<p>Our staff offer their services on a voluntary basis. They consist of scientists, students, but also ordinary citizens who show interest in our projects and share the same passion with us.</p>
<p>For further growth and expansion of our projects, we need funds, resources and support to our organization to be able to survive in these difficult times. Since our establishment, we had no funding from any sources, but instead, our staff contributed with their personal time and money. They all deserve a big thank you and great appreciation from our team.</p>
<p>We are always open for cooperation, and joint activities, and collaboration and support in the development of our new Science Centre, Planetarium and Observatory. </p>
<p>Our methods of teaching and communicating with the public give visitors the opportunity to experience the beauty of the starry sky using simple scientific and entertaining methods and to comprehend the human position in the Solar System and the Universe.</p>
<p>It is impossible to describe by words the excitement of the visitors when they observe the celestial objects through our telescopes. They travel in the world of wonder and are looking forward to learning more. </p>
