</div><div class="block"><p>2015 will be celebrated as the "International Year of Light and Light-based Technologies". The official launch will take place in January with a major official event in Paris, at the headquarters of "UNESCO", which will be attended by many famous physicists and Nobel laureates.</p><p>The aim of the International Year of Light is to highlight, at a global level, how light and the technologies based on it affect every aspect of human life. <span lang="el">More than</span> 85 countries will take part in the related events that will follow during 2015.</p><p>The idea of establishing an International Year of Light (and related technologies) was conceived in 2009 by the European Physical Society, and the relevant decision was taken in 2013 by the UN General Assembly.</p><p>2015 was chosen because it marks the anniversary of several important events: 1,000 years since the publication of a major medieval work on optics by the Muslim scholar Ibn al-Haytham (or Alhazen), 200 years since the publication of Fresnel's landmark work on the wave nature of light, 150 years since Maxwell's decisive work on electromagnetism, which paved the way for modern technologies from lasers and photonics to mobile phones, and 100 years since Einstein's General Theory of Relativity, which incorporated the speed of light as an essential parameter for the description of spacetime.</p><p>The International Year of Light includes a series of hundreds of events around the world, which will bring together various scientists (from astronomers and physicists to doctors and biologists), engineers and artists, with the central aim of promoting the importance of light and optical technologies for society.</p></div></div></div>
