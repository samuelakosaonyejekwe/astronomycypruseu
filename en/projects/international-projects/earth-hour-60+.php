<p><strong>THE STORY BEHIND EARTH HOUR 60+</strong></p>
<p>Started by WWF and partners as a symbolic lights-out event in Sydney in 2007, Earth Hour is now one of the world's largest grassroots movements for the environment. Held every year on the last Saturday of March, Earth Hour engages millions of people in more than 180 countries and territories, switching off their lights to show support for our planet.</p>
<p>But Earth Hour goes far beyond the symbolic action of switching off - it has become a catalyst for positive environmental impact, driving major legislative changes by harnessing the power of the people and collective action.</p>
<p>Earth Hour is open-source and we welcome everyone, anyone, to take part and help amplify our mission to unite people to protect our planet.</p>
<p><strong>EARTH HOUR 60+ MISSION</strong></p>
<p>In 2007, we encouraged people around the world to switch off their lights to call attention to climate change. More than a decade later, the climate crisis remains, made worse by another urgent threat: the rapid loss of biodiversity and nature.</p>
<p>Natural systems are vital for all our futures – and yet, the rate of global loss of nature during the past 50 years is unprecedented in human history. Nature not only provides us food, water, clean air, and other services worth over US$125 trillion a year – it is also one of our strongest allies against climate change. Protecting nature is one of the most immediate, powerful, and cost-effective solutions to the climate crisis.</p>
<p>Today, Earth Hour aims to increase awareness and spark global conversations on protecting nature not only to combat the climate crisis, but to ensure our own health, happiness, prosperity and even survival.</p>
