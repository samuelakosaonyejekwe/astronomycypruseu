<h2>What is World Space Week?</h2>
<p>World Space Week is an international celebration of science and technology, and their contribution to the betterment of the human condition. The United Nations General Assembly declared in 1999 that World Space Week will be held each year from October 4-10. These dates commemorate two events:</p>
<ul>
<li>October 4, 1957: Launch of the first human-made Earth satellite, Sputnik 1, thus opening the way for space exploration</li>
<li>October 10, 1967: The signing of the Treaty on Principles Governing the Activites of States in the Exploration and Peaceful Uses of Outer Space, including the Moon and Other Celestial Bodies.</li>
</ul>
<h2><strong>Where and how is World Space Week celebrated?</strong></h2>
<p>World Space Week consists of space education and outreach events held by space agencies, aerospace companies, schools, planetaria, museums, and astronomy clubs around the world in a common timeframe. These synchronized space events attract greater public and media attention. World Space Week 2025 achieved record scale:</p>
<ul>
<li>Up to 50,000 events</li>
<li>Events in 102 nations</li>
</ul>
<p>World Space Week is coordinated by the United Nations with the support of the World Space Week Association (WSWA). The WSWA leads a global team of National Coordinators, who promote the celebration of World Space Week within their own countries.</p>
<h2><strong>What are the goals of World Space Week?</strong></h2>
<ul>
<li>Provide unique leverage in space outreach and education</li>
<li>Educate people around the world about the benefits that they receive from space</li>
<li>Encourage greater use of space for sustainable economic development</li>
<li>Demonstrate public support for space programs</li>
<li>Excite young people about science, technology, engineering, and math</li>
<li>Foster international cooperation in space outreach and education</li>
</ul>
