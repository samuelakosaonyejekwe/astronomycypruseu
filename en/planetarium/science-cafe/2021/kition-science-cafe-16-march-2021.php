<p>This ONLINE SCIENCE CAFÉ, is about TIME LAPSE PHOTOGRAPHY. </p>
<p>Time-lapse photography is a technique in which the frequency at which film frames are captured (the frame rate)</p>
<p> is much more spread out than the frequency that is used to view the sequence. </p>
<p>When played at normal speed, time appears to be moving faster and thus lapsing.</p>
<p>For example, an image of a scene may be captured at 1 frame per second but then played back at 30 frames per second;</p>
<p>the result is an apparent 30 times speed increase. Similarly, film can also be played at a much lower rate than at which it was captured, which slows down an otherwise fast action, as in slow motion or high-speed photography.</p>

<p>Processes that would normally appear subtle and slow to the human eye,  such as the motion of the Sun and stars in the sky or the growth of a plant, become very pronounced. </p>

