<h2>ABSTRACT</h2>
<h2>COVID-19 as a Case Study for the Discovery of Extraterrestrial Microbial Life.</h2>
<p> The COVID-19 pandemic was a significant event which required a global response to a pathogenic virus. </p>
<p>This event was not just a medical or scientific crisis but relied on politics and required an interdisciplinary approach. </p>
<p>Several years onwards, academics and governments continue to reflect on the lessons learnt from this event. </p>
<p>This paper uses the COVID-19 pandemic as a case study for the discovery of extraterrestrial life, particularly microbial lifeforms. </p>
<p>It investigates the reciprocal relationship between science and policy making in the pandemic drawing on the example of  the World Health Organisation (WHO) Pandemic Agreement and what this reveals about the making of international agreements in the modern world.</p>

<p>It highlights the necessity for international collaboration but recognising that potentially lower stakes  and slower scientific investigatory processes may not provoke the same urgency as seen during COVID-19.</p>

<p>Additionally, the challenge of effective information broadcasting and online (mis)information was rife in the pandemic.</p>
<p>Therefore, by looking at perceptions shaped by science fiction and conspiracy theories about extraterrestrial life  make this case study particularly relevant, providing a valuable analogy for understanding and providing effective science communication. </p>

<p>The paper concludes with addressing the utmost importance for planetary protection  and ratifications of protocols such as those from the likes of COSPAR. </p>

<p>This research does not assume that potential life will be of pathogenic nature but if it is revealed to be harmful to terrestrial life,  the parallels addressed in the research could prove to be even more applicable. </p>

<p>The discovery of extraterrestrial life will have both scientific and political implications  and will carry many of the same political and societal challenges as the COVID-19 pandemic. </p>

<p>The post-pandemic lessons can highlight challenges to be avoided in future global events such as the discovery of extraterrestrial life.</p>
<p>As humanity continues to explore the cosmos and develop an understanding of habitability in space and astrobiology,  precautionary preparations for a discovery must be initiated, not only from a scientific perspective,  but a political one too and the interaction of how their logics and values can inform and influence one another. </p>


