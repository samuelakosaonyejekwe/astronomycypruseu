<p>The topic for November's Online Science Café is “Large Amateur Telescope Making.” </p>
<p>Our guest speaker is Oleg Kryklya from Krasnograd, a small Ukrainian city with negligible level of light pollution.</p>
<p>He will talk about his experience in making telescopes and the observations carried out with them. </p>
<p>Usually, to make a telescope, it is enough to carve a spherical mirror. The case is completely different with a large telescope.</p>
<p>It requires a parabolic mirror. Oleg constracted several telescopes with his own hands, with which he carried out observations both in Ukraine and on different continents. </p>

<p>At the Science Café meeting it will be shown how to go from a glass blank to an astronomical mirror  with a surface of the highest mathematical accuracy; how admiration for the beauties and mysteries of the Cosmos  prompted the building of a parabolic mirror and a telescope, and how this instrument expanded the possibilities of observation.</p>


