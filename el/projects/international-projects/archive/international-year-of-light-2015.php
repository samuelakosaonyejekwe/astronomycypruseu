<p>Το 2015 θα εορταστεί ως το «Διεθνές Έτος Φωτός και Τεχνολογιών με βάση το Φως». Η επίσημη έναρξη θα γίνει εντός του Ιανουαρίου με μεγάλη επίσημη εκδήλωση στο Παρίσι, την έδρα της «UNESCO» όπου θα παρευρεθούν πολλοί διάσημοι φυσικοί και νομπελίστες. </p>
<p>Στόχος του Διεθνούς Έτους Φωτός είναι να αναδείξει, σε παγκόσμιο επίπεδο, τον τρόπο με τον οποίο το φως και οι βασισμένες σε αυτό τεχνολογίες επηρεάζουν κάθε πτυχή της ανθρώπινης ζωής. Στις σχετικές εκδηλώσεις που ακολουθήσουν, εντός του 2015, συμμετάσχουν <span lang="el">περισσότερο από</span> 85 χώρες.</p>
<p>Την ιδέα για την καθιέρωση ενός Διεθνούς Έτους Φωτός (και σχετικών τεχνολογιών) είχε το 2009 η Ευρωπαϊκή Εταιρεία Φυσικής και η σχετική απόφαση ελήφθη το 2013 από τη Γενική Συνέλευση του ΟΗΕ.</p>
<p>Το 2015 επελέγη επειδή αποτελεί επέτειο ορισμένων σημαντικών γεγονότων, όπως τα 1.000 χρόνια από την έκδοση ενός σημαντικού μεσαιωνικού έργου οπτικής από τον μουσουλμάνο Ιμπν αλ- Χαϊθάμ (ή Αλχάζεν), τα 200 χρόνια από τη δημοσίευση της εργασίας- ορόσημο του Φρεσνέλ για την κυματική φύση του φωτός, τα 150 χρόνια από την καθοριστική εργασία του Μάξγουελ για τον ηλεκτρομαγνητισμό, η οποία άνοιξε τον δρόμο για τις σύγχρονες τεχνολογίες από τα λέιζερ και τη φωτονική έως τα κινητά τηλέφωνα, αλλά και τα 100 χρόνια από τη Γενική Θεωρία της Σχετικότητας του Αϊνστάιν, που ενσωμάτωσε την ταχύτητα του φωτός ως ουσιαστική παράμετρο για την περιγραφή του χωροχρόνου.</p>
<p>Το Διεθνές Έτος Φωτός περιλαμβάνει μία σειρά εκατοντάδων εκδηλώσεων ανά τον κόσμο, που θα φέρουν κοντά διάφορους επιστήμονες (από αστρονόμους και φυσικούς έως γιατρούς και βιολόγους), μηχανικούς και καλλιτέχνες, με κεντρικό στόχο να προβληθεί η σημασία του φωτός και των οπτικών τεχνολογιών για την κοινωνία.</p>
<p>Μπορείτε να δείτε το πλήρες ημερολόγιο των προγραμματισμένων εκδηλώσεων στην ιστοσελίδα του Διεθνούς Έτους Φωτός και Τεχνολογιών με βάση το Φως: <a href="http://www.light2015.org" rel="noopener noreferrer" target="_blank">http://www.light2015.org</a></p>
<p>Το ΚΙΤΙΟΝ ΠΛΑΝΗΤΑΡΙΟ &amp; ΑΣΤΕΡΟΣΚΟΠΕΙΟ <span lang="el">είναι Εθνικός Συντονιστής για</span> το Διεθνές Έτος Φωτός και Τεχνολογιών με βάση το Φως στην Κύπρο και θα διοργανώσει εκδηλώσεις ανα το παγκύπριο.</p>
