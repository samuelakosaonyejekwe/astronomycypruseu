<p>Ο σκοτεινός ουρανός γύρω από το Bend είναι ιδανικός για αστρονομία. Στην περιοχή υπάρχουν πολλά εξαιρετικά τηλεσκόπια, καθώς και άνθρωποι που γνωρίζουν καλά τα ουράνια αντικείμενα. Η ομάδα συναντιέται για να κάνει παρατηρήσεις εκλείψεων, βροχών μετεώρων, διελεύσεων, αντικειμένων βαθέος ουρανού και άλλων φαινομένων. Ενημερώνει το κοινό (μερικές φορές ακριβώς στο πεζοδρόμιο), μοιράζεται παρατηρήσεις μέσα από τηλεσκόπια και επισκέπτεται τοπικά αστεροσκοπεία όπως το Pine Mountain και το Sun River. Διοργανώνονται επίσης διαδικτυακές εκδηλώσεις, από την παρακολούθηση ζωντανής μετάδοσης βίντεο από μια απομακρυσμένη έκλειψη έως βιντεοκλήση με αστρονομικό σύλλογο σε άλλη χώρα.</p>
<p>Από το 2015 συνεργαζόμαστε στην πρακτική αστρονομία και στην αρχαιοαστρονομία και τον Αύγουστο του 2017 οργανώσαμε τις παρατηρήσεις της ολικής έκλειψης Ηλίου. Επισκεφθείτε τον επίσημο ιστότοπο του <a href="https://www.meetup.com/Bend-Astronomy-Meetup/" rel="noopener noreferrer" target="_blank">Bend Astronomy Meetup</a> για περισσότερες πληροφορίες.</p>
